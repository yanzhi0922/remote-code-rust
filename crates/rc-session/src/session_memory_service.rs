/// In-memory session memory storage with extraction state tracking.
pub struct SessionMemoryStore {
    /// Memory entries indexed by key.
    entries: BTreeMap<String, MemoryEntry>,
    /// Configuration.
    config: SessionMemoryConfig,
    /// Whether session memory has been initialized.
    initialized: bool,
    /// Token count at last extraction.
    tokens_at_last_extraction: u64,
    /// Whether extraction is currently in progress.
    extraction_in_progress: bool,
    /// Timestamp when extraction started.
    extraction_started_at: Option<u64>,
    /// Total tool calls since last extraction.
    tool_calls_since_last_extraction: u32,
    /// Last summarized message ID.
    last_summarized_message_id: Option<String>,
}

impl Default for SessionMemoryStore {
    fn default() -> Self {
        Self::new(SessionMemoryConfig::default())
    }
}

impl SessionMemoryStore {
    /// Creates a new session memory store with the given configuration.
    #[must_use]
    pub fn new(config: SessionMemoryConfig) -> Self {
        Self {
            entries: BTreeMap::new(),
            config,
            initialized: false,
            tokens_at_last_extraction: 0,
            extraction_in_progress: false,
            extraction_started_at: None,
            tool_calls_since_last_extraction: 0,
            last_summarized_message_id: None,
        }
    }

    /// Returns whether session memory has been initialized.
    #[must_use]
    pub fn is_initialized(&self) -> bool {
        self.initialized
    }

    /// Marks session memory as initialized.
    pub fn mark_initialized(&mut self) {
        self.initialized = true;
    }

    /// Checks if the initialization threshold has been met.
    #[must_use]
    pub fn has_met_initialization_threshold(&self, current_token_count: u64) -> bool {
        current_token_count >= self.config.minimum_message_tokens_to_init
    }

    /// Checks if the update threshold has been met.
    #[must_use]
    pub fn has_met_update_threshold(&self, current_token_count: u64) -> bool {
        let growth = current_token_count.saturating_sub(self.tokens_at_last_extraction);
        growth >= self.config.minimum_tokens_between_update
    }

    /// Records the token count at extraction time.
    pub fn record_extraction_token_count(&mut self, count: u64) {
        self.tokens_at_last_extraction = count;
    }

    /// Increments the tool call counter.
    pub fn record_tool_call(&mut self) {
        self.tool_calls_since_last_extraction += 1;
    }

    /// Returns whether the tool call threshold has been met.
    #[must_use]
    pub fn has_met_tool_call_threshold(&self) -> bool {
        self.tool_calls_since_last_extraction >= self.config.tool_calls_between_updates
    }

    /// Resets the tool call counter after extraction.
    pub fn reset_tool_call_counter(&mut self) {
        self.tool_calls_since_last_extraction = 0;
    }

    /// Marks extraction as started.
    pub fn mark_extraction_started(&mut self) {
        self.extraction_in_progress = true;
        self.extraction_started_at = Some(
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map_or(0, |d| d.as_millis() as u64),
        );
    }

    /// Marks extraction as completed.
    pub fn mark_extraction_completed(&mut self) {
        self.extraction_in_progress = false;
        self.extraction_started_at = None;
    }

    /// Returns whether extraction is currently in progress.
    #[must_use]
    pub fn is_extraction_in_progress(&self) -> bool {
        self.extraction_in_progress
    }

    /// Checks if the current extraction is stale (> 1 minute old).
    #[must_use]
    pub fn is_extraction_stale(&self) -> bool {
        match self.extraction_started_at {
            Some(started) => {
                let now = SystemTime::now()
                    .duration_since(UNIX_EPOCH)
                    .map_or(0, |d| d.as_millis() as u64);
                now.saturating_sub(started) > EXTRACTION_STALE_THRESHOLD_MS
            }
            None => false,
        }
    }

    /// Determines whether memory extraction should happen.
    #[must_use]
    pub fn should_extract_memory(
        &mut self,
        current_token_count: u64,
        has_tool_calls_in_last_turn: bool,
    ) -> bool {
        // Check initialization threshold
        if !self.initialized {
            if !self.has_met_initialization_threshold(current_token_count) {
                return false;
            }
            self.mark_initialized();
        }

        // Check update thresholds
        let has_met_token_threshold = self.has_met_update_threshold(current_token_count);
        let has_met_tool_call_threshold = self.has_met_tool_call_threshold();

        let should_extract = (!has_tool_calls_in_last_turn || has_met_tool_call_threshold)
            && has_met_token_threshold;

        if should_extract {
            self.record_extraction_token_count(current_token_count);
            self.reset_tool_call_counter();
        }

        should_extract
    }

    /// Adds a memory entry.
    pub fn add_entry(&mut self, entry: MemoryEntry) {
        self.entries.insert(entry.key.clone(), entry);
    }

    /// Removes a memory entry by key.
    pub fn remove_entry(&mut self, key: &str) -> Option<MemoryEntry> {
        self.entries.remove(key)
    }

    /// Gets a memory entry by key.
    #[must_use]
    pub fn get_entry(&self, key: &str) -> Option<&MemoryEntry> {
        self.entries.get(key)
    }

    /// Returns all memory entries.
    #[must_use]
    pub fn entries(&self) -> &BTreeMap<String, MemoryEntry> {
        &self.entries
    }

    /// Returns the number of memory entries.
    #[must_use]
    pub fn entry_count(&self) -> usize {
        self.entries.len()
    }

    /// Clears all memory entries.
    pub fn clear(&mut self) {
        self.entries.clear();
    }

    /// Sets the last summarized message ID.
    pub fn set_last_summarized_message_id(&mut self, id: impl Into<String>) {
        self.last_summarized_message_id = Some(id.into());
    }

    /// Returns the last summarized message ID.
    #[must_use]
    pub fn last_summarized_message_id(&self) -> Option<&str> {
        self.last_summarized_message_id.as_deref()
    }

    /// Returns the memory content as a markdown string.
    #[must_use]
    pub fn to_markdown(&self) -> String {
        if self.entries.is_empty() {
            return String::new();
        }

        let mut md = String::from("# Session Memory\n\n");

        // Group by category
        let mut categories: BTreeMap<Option<&str>, Vec<&MemoryEntry>> = BTreeMap::new();
        for entry in self.entries.values() {
            categories
                .entry(entry.category.as_deref())
                .or_default()
                .push(entry);
        }

        for (category, entries) in &categories {
            if let Some(cat) = category {
                md.push_str(&format!("## {cat}\n\n"));
            }
            for entry in entries {
                md.push_str(&format!("- **{}**: {}\n", entry.key, entry.value));
            }
            md.push('\n');
        }

        md
    }

    /// Resets all state (for testing).
    pub fn reset(&mut self) {
        self.entries.clear();
        self.initialized = false;
        self.tokens_at_last_extraction = 0;
        self.extraction_in_progress = false;
        self.extraction_started_at = None;
        self.tool_calls_since_last_extraction = 0;
        self.last_summarized_message_id = None;
    }

    /// Returns a reference to the config.
    #[must_use]
    pub fn config(&self) -> &SessionMemoryConfig {
        &self.config
    }
}

