/// A simplified conversation message for memory extraction.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConversationMessage {
    /// Message role (user, assistant, system).
    pub role: String,
    /// Message text content.
    pub content: String,
    /// Whether this message contains tool calls.
    pub has_tool_calls: bool,
}

impl ConversationMessage {
    /// Creates a new conversation message.
    #[must_use]
    pub fn new(role: impl Into<String>, content: impl Into<String>) -> Self {
        Self {
            role: role.into(),
            content: content.into(),
            has_tool_calls: false,
        }
    }

    /// Creates a message with tool calls flag.
    #[must_use]
    pub fn with_tool_calls(role: impl Into<String>, content: impl Into<String>) -> Self {
        Self {
            has_tool_calls: true,
            ..Self::new(role, content)
        }
    }
}

/// Extracts memories from a list of conversation messages.
///
/// Uses heuristic rules to identify key information:
/// - User's stated goals and tasks
/// - Important decisions and preferences
/// - File paths and code references
/// - Error patterns and solutions
///
/// Returns a list of extracted memory entries.
pub fn extract_memories(messages: &[ConversationMessage]) -> Vec<MemoryEntry> {
    let mut entries = Vec::new();

    for msg in messages {
        if msg.role != "user" {
            continue;
        }

        let content = msg.content.trim();
        if content.is_empty() {
            continue;
        }

        // Extract task/goal statements
        extract_goals(content, &mut entries);

        // Extract file references
        extract_file_references(content, &mut entries);

        // Extract preferences
        extract_preferences(content, &mut entries);
    }

    // Deduplicate by key
    let mut seen = std::collections::HashSet::new();
    entries.retain(|e| seen.insert(e.key.clone()));

    entries
}

/// Extracts goal/task statements from user messages.
fn extract_goals(content: &str, entries: &mut Vec<MemoryEntry>) {
    let goal_patterns = [
        ("i want to ", "goal"),
        ("i need to ", "goal"),
        ("help me ", "goal"),
        ("build ", "task"),
        ("implement ", "task"),
        ("fix ", "task"),
        ("create ", "task"),
        ("add ", "task"),
        ("refactor ", "task"),
    ];

    let lower = content.to_lowercase();
    for (pattern, category) in &goal_patterns {
        if lower.contains(pattern) {
            // Extract the sentence containing the pattern
            if let Some(sentence) = content.split('.').find(|s| s.to_lowercase().contains(pattern))
            {
                let trimmed = sentence.trim();
                if !trimmed.is_empty() && trimmed.len() < 200 {
                    entries.push(
                        MemoryEntry::new(format!("goal_{}", entries.len()), trimmed)
                            .with_category(category.to_string()),
                    );
                }
            }
            break; // One goal per message
        }
    }
}

/// Extracts file path references from messages.
fn extract_file_references(content: &str, entries: &mut Vec<MemoryEntry>) {
    // Simple heuristic: look for common file extensions
    let extensions = [
        ".rs", ".ts", ".js", ".py", ".toml", ".json", ".yaml", ".yml", ".md",
    ];

    for word in content.split_whitespace() {
        let cleaned = word.trim_matches(|c: char| c == '`' || c == '"' || c == '\'' || c == ',');
        if extensions.iter().any(|ext| cleaned.ends_with(ext)) && cleaned.len() < 100 {
            entries.push(
                MemoryEntry::new(format!("file_{}", cleaned.replace('.', "_")), cleaned)
                    .with_category("file_reference"),
            );
        }
    }
}

/// Extracts user preferences from messages.
fn extract_preferences(content: &str, entries: &mut Vec<MemoryEntry>) {
    let pref_patterns = [
        ("i prefer ", "preference"),
        ("use ", "preference"),
        ("don't use ", "preference"),
        ("always ", "preference"),
        ("never ", "preference"),
    ];

    let lower = content.to_lowercase();
    for (pattern, category) in &pref_patterns {
        if lower.contains(pattern) {
            if let Some(sentence) = content.split('.').find(|s| s.to_lowercase().contains(pattern))
            {
                let trimmed = sentence.trim();
                if !trimmed.is_empty() && trimmed.len() < 200 {
                    entries.push(
                        MemoryEntry::new(format!("pref_{}", entries.len()), trimmed)
                            .with_category(category.to_string()),
                    );
                }
            }
            break;
        }
    }
}

/// Loads session memory from a markdown string.
/// Parses the markdown format produced by [`SessionMemoryStore::to_markdown`].
pub fn load_session_memory(markdown: &str) -> Result<SessionMemoryStore> {
    let mut store = SessionMemoryStore::default();

    if markdown.trim().is_empty() {
        return Ok(store);
    }

    let mut current_category: Option<String> = None;

    for line in markdown.lines() {
        let trimmed = line.trim();

        // Category headers
        if let Some(stripped) = trimmed.strip_prefix("## ") {
            current_category = Some(stripped.trim().to_string());
            continue;
        }

        // Skip top-level header
        if trimmed.starts_with("# ") {
            continue;
        }

        // List items: - **key**: value
        if trimmed.starts_with("- **")
            && let Some(rest) = trimmed.strip_prefix("- **")
            && let Some(end_idx) = rest.find("**: ")
        {
            let key = &rest[..end_idx];
            let value = &rest[end_idx + 4..];
            let mut entry = MemoryEntry::new(key, value);
            if let Some(cat) = &current_category {
                entry = entry.with_category(cat.clone());
            }
            store.add_entry(entry);
        }
    }

    store.mark_initialized();
    Ok(store)
}

