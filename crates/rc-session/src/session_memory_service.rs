/// Source of a memory entry.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[derive(Default)]
#[serde(rename_all = "snake_case")]
pub enum MemorySource {
    /// Extracted automatically from conversation.
    #[default]
    AutoExtraction,
    /// Manually added by the user.
    Manual,
    /// Loaded from a previous session.
    PreviousSession,
    /// Generated by a sub-agent.
    SubAgent,
}


/// A single memory entry in the session memory store.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryEntry {
    /// Unique key for this memory.
    pub key: String,
    /// The memory value / content.
    pub value: String,
    /// When this memory was created (epoch millis).
    pub timestamp: u64,
    /// Source of this memory.
    pub source: MemorySource,
    /// Optional category for grouping.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub category: Option<String>,
    /// Relevance score (0.0–1.0) for ranking.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub relevance: Option<f64>,
}

impl MemoryEntry {
    /// Creates a new memory entry with the current timestamp.
    #[must_use]
    pub fn new(key: impl Into<String>, value: impl Into<String>) -> Self {
        Self {
            key: key.into(),
            value: value.into(),
            timestamp: SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map_or(0, |d| d.as_millis() as u64),
            source: MemorySource::AutoExtraction,
            category: None,
            relevance: None,
        }
    }

    /// Creates a new memory entry with a specific source.
    #[must_use]
    pub fn with_source(
        key: impl Into<String>,
        value: impl Into<String>,
        source: MemorySource,
    ) -> Self {
        Self {
            source,
            ..Self::new(key, value)
        }
    }

    /// Creates a manually added memory entry.
    #[must_use]
    pub fn manual(key: impl Into<String>, value: impl Into<String>) -> Self {
        Self::with_source(key, value, MemorySource::Manual)
    }

    /// Sets the category for this entry.
    #[must_use]
    pub fn with_category(mut self, category: impl Into<String>) -> Self {
        self.category = Some(category.into());
        self
    }

    /// Sets the relevance score for this entry.
    #[must_use]
    pub fn with_relevance(mut self, score: f64) -> Self {
        self.relevance = Some(score.clamp(0.0, 1.0));
        self
    }

    /// Returns whether this entry is expired relative to the given TTL.
    #[must_use]
    pub fn is_expired(&self, ttl_ms: u64, now_ms: u64) -> bool {
        if ttl_ms == 0 {
            return false;
        }
        now_ms.saturating_sub(self.timestamp) > ttl_ms
    }
}

