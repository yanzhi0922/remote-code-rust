//! Session Memory Service — automatic conversation memory extraction and storage.
//!
//! Maintains a markdown file with notes about the current conversation.
//! Runs periodically in the background to extract key information
//! without interrupting the main conversation flow.
//!
//! # Architecture
//!
//! - [`SessionMemoryStore`] — in-memory + on-disk memory storage
//! - [`MemoryEntry`] — a single memory entry (key, value, timestamp, source)
//! - [`SessionMemoryConfig`] — configuration for extraction thresholds
//! - [`extract_memories()`] — extracts memories from conversation text
//! - [`load_session_memory()`] — loads session memory from storage

use std::collections::BTreeMap;
use std::time::{SystemTime, UNIX_EPOCH};

use anyhow::Result;
use serde::{Deserialize, Serialize};

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

/// Default minimum context window tokens before initializing session memory.
const DEFAULT_MIN_TOKENS_TO_INIT: u64 = 10_000;

/// Default minimum token growth between updates.
const DEFAULT_MIN_TOKENS_BETWEEN_UPDATE: u64 = 5_000;

/// Default number of tool calls between updates.
const DEFAULT_TOOL_CALLS_BETWEEN_UPDATES: u32 = 3;

/// Default extraction wait timeout in milliseconds.
#[allow(dead_code)]
const EXTRACTION_WAIT_TIMEOUT_MS: u64 = 15_000;

/// Default extraction stale threshold in milliseconds.
const EXTRACTION_STALE_THRESHOLD_MS: u64 = 60_000;

/// Configuration for session memory extraction thresholds.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SessionMemoryConfig {
    /// Minimum context window tokens before initializing session memory.
    pub minimum_message_tokens_to_init: u64,
    /// Minimum context window growth (in tokens) between updates.
    pub minimum_tokens_between_update: u64,
    /// Number of tool calls between session memory updates.
    pub tool_calls_between_updates: u32,
}

impl Default for SessionMemoryConfig {
    fn default() -> Self {
        Self {
            minimum_message_tokens_to_init: DEFAULT_MIN_TOKENS_TO_INIT,
            minimum_tokens_between_update: DEFAULT_MIN_TOKENS_BETWEEN_UPDATE,
            tool_calls_between_updates: DEFAULT_TOOL_CALLS_BETWEEN_UPDATES,
        }
    }
}

impl SessionMemoryConfig {
    /// Creates a new config with custom thresholds.
    #[must_use]
    pub fn new(
        min_tokens_to_init: u64,
        min_tokens_between_update: u64,
        tool_calls_between_updates: u32,
    ) -> Self {
        Self {
            minimum_message_tokens_to_init: min_tokens_to_init,
            minimum_tokens_between_update: min_tokens_between_update,
            tool_calls_between_updates,
        }
    }
}

